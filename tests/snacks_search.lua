-- nvim --headless -u NONE -i NONE -l tests/snacks_search.lua
local dotfiles = vim.fn.getcwd()
vim.opt.rtp:prepend(dotfiles .. "/nvim")
vim.opt.rtp:append(vim.fn.stdpath("data") .. "/lazy/snacks.nvim")
local spec = dofile(dotfiles .. "/nvim/lua/plugins/snacks.lua")
require("snacks").setup(spec.opts)
local search = require("utils.search")
local temporary = vim.fn.tempname()
vim.fn.mkdir(temporary .. "/project/src", "p")
local base = vim.uv.fs_realpath(temporary)
local project = base .. "/project"
assert(vim.system({ "git", "init", "-q", project }):wait().code == 0)
local function write(path, text)
	vim.fn.writefile(vim.split(text, "\n"), base .. "/" .. path)
end
write("project/root.md", "한국어 root userController\nuser.name\nuserXname")
write("project/src/local.ts", "한국어 local userController\nlocal only")
write("project/.hidden.md", "한국어 hidden")
write("project/ignored.env", "한국어 ignored")
write("project/.gitignore", "ignored.env")
write("project/.git/search-probe", "한국어 metadata")
write("outside.md", "한국어 outside")
vim.cmd.edit(project .. "/src/local.ts")
vim.cmd.cd(base)
local function settle(p)
	vim.wait(40)
	assert(vim.wait(5000, function()
		return not p.finder:running() and not p.matcher:running()
	end, 10), "picker did not settle")
	return p
end
local function paths(p)
	settle(p)
	local ret = {}
	for _, item in ipairs(p:items()) do
		ret[#ret + 1] = item.file
	end
	return ret
end
local function contains(p, suffix)
	for _, path in ipairs(paths(p)) do
		if path:sub(-#suffix) == suffix then return true end
	end
	return false
end
local function close(p)
	p:close()
	vim.wait(30)
end
local function query(p, value)
	settle(p)
	vim.api.nvim_buf_set_lines(p.input.win.buf, 0, -1, false, { value })
	if p.opts.live then p.input.filter.search = value else p.input.filter.pattern = value end
	p:find()
	settle(p)
end
local function key(p, lhs)
	local rhs = vim.api.nvim_win_call(p.input.win.win, function()
		return assert(vim.fn.maparg(lhs, "i", false, true).callback, lhs .. " is unmapped")
	end)
	vim.api.nvim_win_call(p.input.win.win, rhs)
	settle(p)
end
assert(search.directory() == project)
assert(search.directory(true) == project .. "/src")
local p = search.files()
assert(p:cwd() == project)
assert(contains(p, ".hidden.md"))
assert(not contains(p, "ignored.env"))
assert(not contains(p, ".git/search-probe"))
key(p, "<C-e>")
assert(p.opts.ignored and contains(p, "ignored.env"))
assert(not contains(p, ".git/search-probe"))
key(p, "<C-h>")
assert(not p.opts.hidden and not contains(p, ".hidden.md"))
query(p, "local")
p.list:move(1)
local cursor = p.list.cursor
close(p)
p = settle(Snacks.picker.resume())
assert(p:cwd() == project and p.opts.ignored and not p.opts.hidden)
assert(p.input.filter.pattern == "local" and p.list.cursor == cursor)
close(p)
p = search.files(true)
assert(p:cwd() == project .. "/src" and contains(p, "local.ts"))
assert(not contains(p, "root.md"))
assert(p.opts.hidden and not p.opts.ignored)
close(p)
p = search.grep()
assert(p.opts.regex and p.opts.live and p:cwd() == project)
query(p, "한국어")
assert(#paths(p) == 3)
key(p, "<C-e>")
assert(#paths(p) == 4 and not contains(p, ".git/search-probe"))
key(p, "<C-g>")
assert(not p.opts.live)
query(p, "file:lclts")
assert(#paths(p) == 1 and contains(p, "local.ts"))
key(p, "<C-g>")
assert(p.opts.live and p.input.filter.search == "한국어")
close(p)
p = search.grep()
query(p, "user.name -- --glob=*.md")
assert(#paths(p) == 2)
key(p, "<C-x>")
assert(not p.opts.regex and #paths(p) == 1)
close(p)
p = settle(Snacks.picker.resume())
assert(not p.opts.regex and #paths(p) == 1)
close(p)
p = search.grep(true)
query(p, "한국어")
assert(#paths(p) == 1 and contains(p, "local.ts"))
local setreg = vim.fn.setreg
local copied
vim.fn.setreg = function(reg, value) assert(reg == "+"); copied = value end
key(p, "<C-o>")
vim.fn.setreg = setreg
assert(copied == "project/src/local.ts", "copy used editor cwd instead of item cwd: " .. tostring(copied))
close(p)
vim.api.nvim_win_set_cursor(0, { 1, 0 })
p = search.grep(false, true)
assert(p.input.filter.search == "한국어" and not p.opts.regex and p.opts.live)
assert(#paths(p) == 3)
close(p)
vim.api.nvim_buf_set_lines(0, 0, -1, false, { "user.name" })
vim.api.nvim_win_set_cursor(0, { 1, 0 })
vim.cmd("normal! v$")
p = search.grep()
assert(p.input.filter.search == "user.name" and not p.opts.regex)
assert(#paths(p) == 1)
close(p)
vim.cmd("normal! \27")
vim.bo.modified = false
vim.cmd.edit(base .. "/outside.md")
p = search.recent()
assert(not contains(p, project .. "/root.md"))
close(p)
vim.cmd.edit(project .. "/root.md")
p = search.recent()
assert(contains(p, "local.ts") and not contains(p, "outside.md"))
close(p)
p = search.recent(true)
assert(contains(p, "outside.md"))
close(p)
vim.cmd.enew()
assert(search.directory() == base and search.directory(true) == base)
vim.cmd.edit(project .. "/root.md")
p = search.grep()
query(p, "한국어")
p.list:select(p:items()[1])
p:action("qflist")
vim.wait(40)
assert(#vim.fn.getqflist() == 1, "quickfix must use selected results")
vim.cmd.cclose()
p = search.grep()
query(p, "한국어")
p:action("qflist")
vim.wait(40)
assert(#vim.fn.getqflist() == 3, "quickfix must use all results without selection")
vim.cmd.cclose()
p = search.files(true)
query(p, "local")
p:action("edit_vsplit")
vim.wait(100)
assert(vim.api.nvim_buf_get_name(0) == project .. "/src/local.ts")
assert(#vim.api.nvim_list_wins() == 2)
vim.cmd.only()
vim.api.nvim_buf_set_lines(0, 0, -1, false, { "unsaved" })
local modified = vim.api.nvim_get_current_buf()
p = Snacks.picker.buffers()
settle(p)
local confirm = vim.fn.confirm
local prompted = false
vim.fn.confirm = function() prompted = true; return 3 end
for i, item in ipairs(p:items()) do
	if item.buf == modified then p.list:move(i, true, true); break end
end
key(p, "<C-d>")
vim.fn.confirm = confirm
assert(prompted and vim.api.nvim_buf_is_loaded(modified) and vim.bo[modified].modified)
close(p)

vim.api.nvim_buf_set_lines(modified, 0, -1, false, { "미저장 userController" })
p = settle(Snacks.picker.lines())
query(p, "usrctrl")
assert(#p:items() == 1 and p:items()[1].text == "미저장 userController")
local preview_hidden = p.layout:is_hidden("preview")
key(p, "<F2>")
assert(p.layout:is_hidden("preview") ~= preview_hidden, "F2 did not toggle preview")
key(p, "<F2>")
assert(p.layout:is_hidden("preview") == preview_hidden, "F2 did not restore preview")
key(p, "<F3>")
assert(p.layout.opts.fullscreen, "F3 did not maximize")
key(p, "<F3>")
assert(not p.layout.opts.fullscreen, "F3 did not restore layout")
close(p)
p = search.grep_buffers()
query(p, "미저장")
assert(#paths(p) == 0, "grep_buffers must search saved content")
query(p, "한국어")
assert(contains(p, "local.ts") and contains(p, "outside.md"))
close(p)
p = search.smart()
assert(p:cwd() == project)
assert(contains(p, "local.ts") and contains(p, "root.md") and contains(p, ".hidden.md"))
assert(not contains(p, "outside.md"))
local seen = {}
for _, item in ipairs(p:items()) do
	local path = Snacks.picker.util.path(item)
	assert(not seen[path], "smart search duplicated " .. path)
	seen[path] = true
end
close(p)
p = settle(Snacks.picker.keymaps())
assert(#p:items() > 0)
close(p)
p = settle(Snacks.picker.pickers())
query(p, "command_history")
assert(#p:items() == 1)
close(p)
vim.fn.delete(base, "rf")
print("PASS: search scopes, hidden/ignore, Korean, regex, resume, selection, smart, unsaved lines, open files, menus and layout keys")
vim.cmd("qa!")
